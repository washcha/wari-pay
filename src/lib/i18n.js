export const formatMessage = (message, values = {}) => (
  String(message || '').replace(/\{(\w+)\}/g, (_, key) => values[key] ?? '')
)

export const translate = (language, key, values) => {
  const parts = key.split('.')
  let current = translations[language] || translations[DEFAULT_LANGUAGE]
  for (const part of parts) current = current?.[part]

  if (typeof current !== 'string') {
    current = parts.reduce((value, part) => value?.[part], translations[DEFAULT_LANGUAGE])
  }

  return formatMessage(current || key, values)
}
