export const LANGUAGES = [
  { code: 'zh-TW', label: '繁體中文', nativeLabel: '繁體中文' },
  { code: 'en', label: 'English', nativeLabel: 'English' },
  { code: 'ja', label: 'Japanese', nativeLabel: '日本語' },
  { code: 'ko', label: 'Korean', nativeLabel: '한국어' },
]

export const DEFAULT_LANGUAGE = 'zh-TW'
export const LANGUAGE_STORAGE_KEY = 'wari_language'

export const normalizeLanguage = (language = '') => {
  const lower = language.toLowerCase()
  if (lower.startsWith('zh')) return 'zh-TW'
  if (lower.startsWith('ja')) return 'ja'
  if (lower.startsWith('ko')) return 'ko'
  if (lower.startsWith('en')) return 'en'
  return DEFAULT_LANGUAGE
}

export const getUrlLanguage = () => {
  if (typeof window === 'undefined') return null
  const lang = new URLSearchParams(window.location.search).get('lang')
  const normalized = normalizeLanguage(lang || '')
  return lang && LANGUAGES.some(language => language.code === normalized) ? normalized : null
}

export const detectDeviceLanguage = () => {
  if (typeof navigator === 'undefined') return DEFAULT_LANGUAGE
  const candidates = navigator.languages?.length ? navigator.languages : [navigator.language]
  return normalizeLanguage(candidates.find(Boolean))
}

export const getSavedLanguage = () => {
  if (typeof localStorage === 'undefined') return null
  const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY)
  const normalized = normalizeLanguage(saved || '')
  return saved && LANGUAGES.some(language => language.code === normalized) ? normalized : null
}

export const saveLanguage = (language) => {
  if (typeof localStorage === 'undefined') return
  localStorage.setItem(LANGUAGE_STORAGE_KEY, normalizeLanguage(language))
}

